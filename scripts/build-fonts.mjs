// 构建前生成字体子集。
//
// 背景：Fontsource 的中文包是「单体」文件（每个字重 1.5MB，且没有 unicode-range），
// 浏览器必须整个下完才显示中文，导致明显的 FOUT 与回流。
// 而按 unicode-range 切片的方案对「长中文文章」几乎无效——一页就有几百个不同汉字，
// 会横跨 20+ 个切片 × 多个字重，实测反而更慢。
//
// 所以这里按「站点实际用到的字符」裁剪：读取 src/ 下所有文本，
// 用 subset-font 从 Fontsource 源字体裁出子集，每个字重只留一个几万字节的文件。
//
// 用法：node scripts/build-fonts.mjs（已被 npm run dev / build 自动调用）
// 产物：public/fonts/*.woff2 + public/fonts/fonts.css + public/fonts/manifest.json
//       public/fonts/ 在 .gitignore 中，每次构建重新生成 —— 新增文章时字符自动包含。
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import subsetFont from 'subset-font';

const SRC_DIR = path.resolve('src');
const EXTRA_TEXT_FILES = ['public/llms.txt'];
const OUT_DIR = path.resolve('public/fonts');
const TEXT_EXT = /\.(md|mdx|astro|ts|js|mjs|css|json|txt)$/;

// ASCII 可打印字符始终包含，避免运行时新增的日期/序号等缺字
const ASCII = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('');

// 中文标点兜底（即使当前文章没用到，也留一份，避免以后写作时缺字）
const CJK_PUNCT =
  '、。〃〈〉《》「」『』【】〔〕〖〗〘〙〚〛〜〝〞〟〰〾〿' +
  '‐‑‒–—―‖‗‘’‚‛“”„‟…‧﹏！＂＃＄％＆＇（）＊＋，－．／：；＜＝＞？＠［＼］＾＿｀｛｜｝～';

const FONTS = [
  {
    family: 'Noto Serif SC',
    slug: 'noto-serif-sc',
    kind: 'cjk',
    variants: [
      // 中文只保留 400 / 700：
      //  - 中文没有 500 字面，用 500 的中文本来就被浏览器就近匹配到 400
      //  - 600 与 700 差别很小，去掉 600 可省下约 1/3 的中文字体体积
      // 所以中文元素请只用 400 或 700（见 global.css 与 works.astro）
      { weight: 400, style: 'normal', src: 'node_modules/@fontsource/noto-serif-sc/files/noto-serif-sc-chinese-simplified-400-normal.woff2' },
      { weight: 700, style: 'normal', src: 'node_modules/@fontsource/noto-serif-sc/files/noto-serif-sc-chinese-simplified-700-normal.woff2' },
    ],
  },
  {
    family: 'EB Garamond',
    slug: 'eb-garamond',
    kind: 'latin',
    variants: [
      ...[400, 500, 600, 700].flatMap((weight) => [
        { weight, style: 'normal', src: `node_modules/@fontsource/eb-garamond/files/eb-garamond-latin-${weight}-normal.woff2` },
        { weight, style: 'italic', src: `node_modules/@fontsource/eb-garamond/files/eb-garamond-latin-${weight}-italic.woff2` },
      ]),
    ],
  },
];

async function walk(dir, acc = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(full, acc);
    else if (TEXT_EXT.test(entry.name)) acc.push(full);
  }
  return acc;
}

/** 收集站点实际会渲染出来的所有字符 */
async function collectChars() {
  let text = '';
  for (const file of await walk(SRC_DIR)) text += await readFile(file, 'utf8');
  for (const file of EXTRA_TEXT_FILES) {
    try {
      text += await readFile(path.resolve(file), 'utf8');
    } catch {
      /* 可选文件，缺失就跳过 */
    }
  }

  const chars = new Set(text);
  const latin = new Set(ASCII);
  const cjk = new Set();

  for (const ch of chars) {
    const cp = ch.codePointAt(0);
    // 跳过控制字符（\n \t \r 等）—— 它们不需要字形。
    // 尤其是 \r：本地文件是 CRLF、CI 检出按 .gitattributes 是 LF，
    // 若把它算进字符集，本地与 Cloudflare 生成的拉丁子集就会不一致（哈希对不上）。
    if (cp < 0x20 || cp === 0x7f) continue;
    // 0x2E80 以下（ASCII、拉丁扩展、通用标点）交给 EB Garamond
    if (cp < 0x2e80) latin.add(ch);
    // 汉字、假名、全角形式交给思源宋体
    else cjk.add(ch);
    // 通用标点两侧都带上，避免中英文混排时落到不合适的字体
    if (cp >= 0x2000 && cp < 0x2e80) cjk.add(ch);
  }
  for (const ch of CJK_PUNCT) cjk.add(ch);

  return { latin: [...latin].sort().join(''), cjk: [...cjk].sort().join('') };
}

async function main() {
  const { latin, cjk } = await collectChars();
  console.log(`[build-fonts] 站点字符：拉丁 ${latin.length} 个、中日韩 ${cjk.length} 个`);

  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  // 不写中文注释：这段 CSS 会被内联进每个页面
  const css = ['/* generated by scripts/build-fonts.mjs */'];
  const manifest = { preload: [] };
  let total = 0;

  for (const font of FONTS) {
    const text = font.kind === 'cjk' ? cjk : latin;

    for (const variant of font.variants) {
      const source = await readFile(variant.src);
      const out = await subsetFont(source, text, { targetFormat: 'woff2' });
      const hash = createHash('sha1').update(out).digest('hex').slice(0, 8);
      const name = `${font.slug}-${variant.weight}-${variant.style}.${hash}.woff2`;
      await writeFile(path.join(OUT_DIR, name), out);
      total += out.length;

      css.push(
        '@font-face{',
        `font-family:'${font.family}';`,
        `font-style:${variant.style};`,
        `font-weight:${variant.weight};`,
        'font-display:swap;',
        `src:url(/fonts/${name}) format('woff2')`,
        '}',
      );

      // 每个字族的常规字重 400 作为首屏预加载候选
      if (variant.weight === 400 && variant.style === 'normal') {
        manifest.preload.push(`/fonts/${name}`);
      }
      console.log(
        `[build-fonts]   ${font.family} ${variant.weight} ${variant.style}: ` +
          `${(source.length / 1024).toFixed(0)}KB → ${(out.length / 1024).toFixed(1)}KB`,
      );
    }
  }

  await writeFile(path.join(OUT_DIR, 'fonts.css'), css.join(''));
  await writeFile(path.join(OUT_DIR, 'manifest.json'), JSON.stringify(manifest));
  console.log(`[build-fonts] 完成：${FONTS.flatMap((f) => f.variants).length} 个文件，合计 ${(total / 1024).toFixed(0)} KB`);
}

main().catch((err) => {
  console.error('[build-fonts] 失败：', err.message);
  process.exit(1);
});
